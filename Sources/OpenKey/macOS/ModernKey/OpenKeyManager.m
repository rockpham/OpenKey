#import "OpenKeyManager.h"

extern void OpenKeyInit(void);

extern CGEventRef OpenKeyCallback(CGEventTapProxy proxy,
                                  CGEventType type,
                                  CGEventRef event,
                                  void *refcon);

extern NSString* ConvertUtil(NSString* str);

@interface OpenKeyManager ()

@end

@implementation OpenKeyManager {

}
static BOOL _isInited = NO;

static CFMachPortRef      eventTap;
static CGEventMask        eventMask;
static CFRunLoopSourceRef runLoopSource;
static NSTimer*           eventTapWatchdogTimer = nil;

+(BOOL)isInited {
    return _isInited;
}

+(void)startWatchdogTimer {
    if (eventTapWatchdogTimer == nil) {
        eventTapWatchdogTimer = [NSTimer scheduledTimerWithTimeInterval:0.5
                                                                 repeats:YES
                                                                   block:^(NSTimer * _Nonnull timer) {
            if (eventTap != nil && !CGEventTapIsEnabled(eventTap)) {
                NSLog(@"[OpenKey] Watchdog: event tap disabled, re-enabling...");
                CGEventTapEnable(eventTap, true);
            }
        }];
    }
}

+(void)stopWatchdogTimer {
    if (eventTapWatchdogTimer != nil) {
        [eventTapWatchdogTimer invalidate];
        eventTapWatchdogTimer = nil;
    }
}

+(BOOL)initEventTap {
    if (_isInited)
        return true;
    
    //init modernKey
    OpenKeyInit();
    
    // Create an event tap. We are interested in key presses and mouse clicks.
    eventMask = ((1 << kCGEventKeyDown) |
                 (1 << kCGEventKeyUp) |
                 (1 << kCGEventFlagsChanged) |
                 (1 << kCGEventLeftMouseDown) |
                 (1 << kCGEventRightMouseDown));
    
    eventTap = CGEventTapCreate(kCGSessionEventTap,
                                kCGHeadInsertEventTap,
                                0,
                                eventMask,
                                OpenKeyCallback,
                                NULL);
    
    if (!eventTap) {
        
        fprintf(stderr, "failed to create event tap\n");
        return NO;
    }
    
    _isInited = YES;
    
    // Create a run loop source.
    runLoopSource = CFMachPortCreateRunLoopSource(kCFAllocatorDefault, eventTap, 0);
    
    // Add to the current run loop.
    CFRunLoopAddSource(CFRunLoopGetCurrent(), runLoopSource, kCFRunLoopCommonModes);
    
    // Enable the event tap. The source is on the main run loop, which
    // NSApplication is already running — calling CFRunLoopRun() here would
    // start a nested loop that blocks AppKit from processing UI events.
    CGEventTapEnable(eventTap, true);
    
    // Start watchdog timer to keep event tap always alive
    [self startWatchdogTimer];
    
    return YES;
}

+(BOOL)stopEventTap {
    if (_isInited) { //release all object
        [self stopWatchdogTimer];

        CFRunLoopRemoveSource(CFRunLoopGetCurrent(), runLoopSource, kCFRunLoopCommonModes);
        CFRelease(runLoopSource);
        runLoopSource = nil;
        
        CFMachPortInvalidate(eventTap);
        CFRelease(eventTap);
        eventTap = nil;
        
        _isInited = false;
    }
    return YES;
}

+(void)reEnableEventTap {
    if (eventTap != nil) {
        CGEventTapEnable(eventTap, true);
        dispatch_async(dispatch_get_main_queue(), ^{
            if (eventTap != nil && !CGEventTapIsEnabled(eventTap)) {
                CGEventTapEnable(eventTap, true);
            }
        });
    }
}

